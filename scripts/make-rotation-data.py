#!/usr/bin/env python3
"""Write src/data/rotation.ts: each star's projected rotation speed (v sin i) from the Yale Bright Star Catalogue, for the stars src/data/stars.ts holds.

Source: the same catalogue and file as scripts/make-star-data.py (Hoffleit and Warren 1991, 5th revised edition, preliminary, ADC V/50, as NASA's HEASARC
serves it), its columns `rotvel` (km/s), `rotvel_comm` ("<" or "=<": an upper limit) and `rotvel_uncert` (":" uncertain). v sin i is the equator's speed
times the sine of the angle between the spin axis and the line of sight: the true speed is that or more, and the axis's tilt is not known from it.

    python3 -I scripts/make-rotation-data.py                 # fetches HEASARC's heasarc_bsc5p.tdat.gz (needs the network)
    python3 -I scripts/make-rotation-data.py --from FILE     # reads that file saved earlier, gzipped or not

It does not run in the test.
"""
import gzip
import sys
import urllib.request
from pathlib import Path

LIMIT = 6.0
SOURCE = "https://heasarc.gsfc.nasa.gov/FTP/heasarc/dbase/tdat_files/heasarc_bsc5p.tdat.gz"
ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "data" / "rotation.ts"


def unpack(data: bytes) -> str:
    return (gzip.decompress(data) if data[:2] == b"\x1f\x8b" else data).decode("latin-1")


def records(text: str):
    """The rows of a HEASARC tdat file as dictionaries keyed by its column names (`line[1]`)."""
    lines = text.splitlines()
    columns = next(line for line in lines if line.startswith("line[1]")).split("=", 1)[1].split()
    start = lines.index("<DATA>") + 1
    for line in lines[start:]:
        if line.startswith("<END>"):
            break
        yield dict(zip(columns, line.split("|")))


def main() -> None:
    if "--from" in sys.argv:
        text = unpack(Path(sys.argv[sys.argv.index("--from") + 1]).read_bytes())
    else:
        with urllib.request.urlopen(SOURCE, timeout=120) as response:
            text = unpack(response.read())
    table = (ROOT / "src" / "data" / "stars.ts").read_text(encoding="utf-8").split("STAR_ROWS = `", 1)[1].split("`", 1)[0]
    ours = {int(row.split("|", 1)[0]) for row in table.splitlines()}
    rows = []
    for r in records(text):
        if not r["hr"].strip() or int(r["hr"]) not in ours or not r["rotvel"].strip():
            continue
        flag = "<" if "<" in r["rotvel_comm"] else ":" if ":" in r["rotvel_uncert"] else ""
        rows.append((int(r["hr"]), int(r["rotvel"]), flag))
    rows.sort()
    body = "\n".join(f"{hr}|{speed}|{flag}" for hr, speed, flag in rows)
    out = f"""// GENERATED by scripts/make-rotation-data.py. Do not edit by hand.
// Projected rotation speeds (v sin i) from the Yale Bright Star Catalogue (Hoffleit and Warren 1991, 5th revised edition, preliminary; ADC V/50, from NASA HEASARC),
// for the {len(rows)} stars of src/data/stars.ts that have one. One row a star: HR number | v sin i in km/s | "<" where it is an upper limit, ":" where the catalogue marks it uncertain.

/** The rotation rows, one per line, by HR number. */
export const ROTATION_ROWS = `{body}`;
"""
    OUT.write_text(out, encoding="utf-8")
    print(f"wrote {OUT} ({len(rows)} stars)")


if __name__ == "__main__":
    main()
