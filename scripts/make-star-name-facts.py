#!/usr/bin/env python3
"""Write src/data/star-name-facts.ts: for each of the 335 stars the package gives a common name, the day the IAU Working Group on Star Names approved the name and the language the name comes from.

Sources, both read on 2026-11-18 and kept outside the repository (the folder given with --from):
- "iau-csn": the IAU Catalog of Star Names (IAU-CSN), https://www.pas.rochester.edu/~emamajek/WGSN/IAU-CSN.txt, last updated 2022-04-04. The IAU says its products are released under Creative Commons Attribution: the day each name was approved,
  matched to the package's names by the name (ignoring case, accents and spaces).
- "wikipedia-star-names": English Wikipedia, "List of proper names of stars", the column "Name origin" (https://en.wikipedia.org/wiki/List_of_proper_names_of_stars, CC BY-SA 4.0): one word for the language or culture a name comes from, as the
  table writes it. Nothing else of the table is kept: not its notes, its meanings or its pronunciations.
A name that the IAU-CSN does not hold has no day (flag `u`): the package's own list has three (Navi, Men and Rutilicus); and a name the table has no origin for has none.

    python3 -I scripts/make-star-name-facts.py --from DIR     # DIR holds IAU-CSN.txt and List_of_proper_names_of_stars.wikitext

None of this runs in the test.
"""
from __future__ import annotations
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "data" / "star-name-facts.ts"


def norm(text: str) -> str:
    return re.sub(r"[^a-z0-9]", "", unicodedata.normalize("NFKD", text).lower())


def names() -> dict[int, str]:
    text = (ROOT / "src" / "data" / "stars.ts").read_text(encoding="utf-8")
    block = re.search(r"STAR_NAMES[^=]*= \{ (.*?) \};", text, re.S).group(1)
    return {int(hr): name for hr, name in re.findall(r'(\d+):"([^"]+)"', block)}


def approved(folder: Path) -> dict[str, str]:
    out = {}
    for line in (folder / "IAU-CSN.txt").read_text(encoding="utf-8").split("\n"):
        if not line.strip() or line[0] in "#$":
            continue
        day = re.search(r"(\d{4}-\d\d-\d\d)", line)
        if day:
            out[norm(line[:18].strip())] = day.group(1)
            out[norm(line[18:36].strip())] = day.group(1)
    return out


def clean(cell: str) -> str:
    cell = re.sub(r"<ref[^>]*>.*?</ref>|<ref[^>]*/>", "", cell, flags=re.S)
    cell = re.sub(r"\{\{[^}]*\}\}", "", cell)
    cell = re.sub(r"\[\[(?:[^\]|]*\|)?([^\]]*)\]\]", r"\1", cell)
    cell = re.sub(r"<[^>]+>", " ", cell).replace("'''", "").replace("''", "")
    return re.sub(r"\s+", " ", cell).strip()


def origins(folder: Path) -> dict[str, str]:
    text = (folder / "List_of_proper_names_of_stars.wikitext").read_text(encoding="utf-8")
    start = text.index('{| class="wikitable sortable')
    body = text[start:text.index("\n|}", start)]
    out = {}
    for row in re.split(r"\n\|-", body)[1:]:
        cells = [c.lstrip("|").strip() for c in re.split(r"\n\||\|\|", row.strip()) if c.strip() != ""]
        if len(cells) >= 4:
            name, origin = clean(cells[0]).replace("†", "").strip(), clean(cells[3])
            if name and origin and "|" not in origin:
                out[norm(name)] = origin
    return out


def main() -> None:
    folder = Path(sys.argv[sys.argv.index("--from") + 1]).expanduser()
    given, day, origin = names(), approved(folder), origins(folder)
    rows, no_day, no_origin = [], [], []
    for hr in sorted(given):
        key = norm(given[hr])
        when, language = day.get(key, ""), origin.get(key, "")
        flags = "" if when else "u"
        if not when:
            no_day.append(given[hr])
        if not language:
            no_origin.append(given[hr])
        rows.append("|".join([str(hr), when, language, flags]))
    header = """// GENERATED by scripts/make-star-name-facts.py. Do not edit by hand.
// For each star with a common name: the day the IAU Working Group on Star Names approved the name (IAU Catalog of Star Names, updated 2022-04-04, read 2026-11-18; the IAU releases it under Creative Commons Attribution) and the language
// or culture the name comes from (English Wikipedia's "List of proper names of stars", column "Name origin", CC BY-SA 4.0: one word, nothing else of the table). One row a star: HR number | day approved (empty where the catalogue does not hold the name) |
// origin (empty where the table gives none) | flags (`u`: the IAU-CSN does not hold the name).
"""
    OUT.write_text(header + f"\n/** The named stars' facts, one per line, by HR number. */\nexport const STAR_NAME_FACTS = `{chr(10).join(rows)}`;\n", encoding="utf-8")
    print(f"wrote {len(rows)} rows; no approval day for {len(no_day)}: {no_day}; no origin for {len(no_origin)}: {no_origin}")


if __name__ == "__main__":
    main()
