// Write src/data/names-named.ts: the fields of the 335 stars that have a common name, with the id each has in the full names index, for the small `/names/named` chunk.
//
// The ids are settled over all 5,080 stars and the Messier objects (two stars with the same name or designation each take their catalogue number), so they are read from the full index here and
// stored, and the small chunk needs no star table. The other fields are the Bright Star Catalogue's, as `/stars` holds them; no new data. The test re-runs this with `--check`.
//
//     node scripts/make-names-named.ts            # write the table
//     node scripts/make-names-named.ts --check    # exit 1 if the table on disk is not what this would write
//
// Never reaches the network.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { nameRows } from "../src/names.ts";
import { stars } from "../src/stars.ts";

const FILE = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "data", "names-named.ts");

const ids = new Map(nameRows({ kinds: ["star"] }).map((row) => [row.hr!, row.id]));
const named = stars().filter((star) => star.name !== undefined).sort((a, b) => a.hr - b.hr);
const rows = named.map((star) => {
  for (const text of [star.name!, star.nameJa ?? "", star.designation ?? "", star.spectralType]) if (text.includes("|") || text.includes("\n")) throw new Error(`HR ${star.hr}: "${text}" holds a separator`);
  return [ids.get(star.hr)!, star.hr, star.name, star.nameJa ?? "", star.designation ?? "", star.constellation, star.rightAscension, star.declination, star.magnitude, star.spectralType].join("|");
});

const text = `// GENERATED by scripts/make-names-named.ts. Do not edit by hand.
// The ${rows.length} stars with a common name, in the fields a names row is made from, for \`@johnmorrisdotca/hoshi-stars/names/named\`: the Bright Star Catalogue's, as \`/stars\` holds them (Yale, with credit: NOTICE.md), and the id each has in
// the full names index. One row a star, by HR number: id | HR | name | name in katakana | designation | constellation | right ascension | declination (J2000 degrees) | magnitude | spectral type.
export const NAMED_STAR_ROWS = \`${rows.join("\n")}\`;
`;

if (process.argv.includes("--check")) {
  if (readFileSync(FILE, "utf8") !== text) {
    console.error("src/data/names-named.ts is not what scripts/make-names-named.ts writes: run it again.");
    process.exit(1);
  }
  console.log(`ok   src/data/names-named.ts holds the ${rows.length} named stars`);
} else {
  writeFileSync(FILE, text);
  console.log(`wrote src/data/names-named.ts: ${rows.length} stars, ${text.length} bytes`);
}
