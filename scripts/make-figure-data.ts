// Writes src/data/figures.ts from the drawings in scripts/figure-sources.ts: each is a path drawn on a flat chart of degrees around the figure's centre (stereographic, north up, east to the left),
// with stars as anchors (`@Dubhe`, or `@Dubhe:0.5,-1` for a point offset from one), turned into right ascension and declination in J2000. Run: node scripts/make-figure-data.ts
// A drawing is strokes: `R` a smooth curve through the points that follow (it lists its start first), `O` the same closed, and `M p L q r` straight lines from p. `#` starts a comment.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { constellation } from "../src/constellations.ts";
import { project, unproject } from "../src/projection.ts";
import { starByHr, starByName } from "../src/stars.ts";
import { SOURCES } from "./figure-sources.ts";

type Pair = [number, number];

function sky(source: (typeof SOURCES)[number]): { local: (x: number, y: number) => Pair; at: (token: string) => Pair } {
  const options = { centre: { rightAscension: source.centre[0], declination: source.centre[1] }, scale: 180 / Math.PI, rotation: source.rotation };
  return {
    local: (x, y) => {
      const p = unproject("stereographic", { x, y }, options)!;
      return [p.rightAscension, p.declination];
    },
    at: (token) => {
      const [name, offset] = token.slice(1).split(":") as [string, string | undefined];
      const star = /^HR\d+$/.test(name) ? starByHr(Number(name.slice(2))) : starByName(name.replaceAll("_", " "));
      if (star === undefined) throw new Error(`${source.id}: no star "${name}"`);
      const p = project("stereographic", star, options)!;
      const [dx, dy] = offset === undefined ? [0, 0] : offset.split(",").map(Number);
      return [p.x + dx!, p.y + dy!];
    },
  };
}

function flat(source: (typeof SOURCES)[number]): string {
  const { at, local } = sky(source);
  const factor = 10 ** (source.digits ?? 2);
  const round = (v: number): number => Math.round(v * factor) / factor;
  const text = (v: number): string => String(round(v));
  const words = source.path.replace(/#.*$/gm, "").split(/\s+/).filter((w) => w !== "");
  const done: Array<{ kind: string; points: Pair[] }> = [];
  for (const word of words) {
    if (/^[MLRO]$/.test(word)) done.push({ kind: word, points: [] });
    else if (word.startsWith("@")) done.at(-1)!.points.push(at(word));
    else {
      const [x, y] = word.split(",").map(Number);
      if (x === undefined || y === undefined || !Number.isFinite(x) || !Number.isFinite(y)) throw new Error(`${source.id}: bad point "${word}"`);
      done.at(-1)!.points.push([x, y]);
    }
  }
  let out = "";
  let previousRa = 0;
  let begin: Pair = [0, 0];
  for (const { kind, points: listed } of done) {
    if (kind === "M") {
      begin = listed[0]!;
      continue;
    }
    const points = kind === "L" ? [begin, ...listed] : listed;
    if (points.length < 2 && kind !== "O") throw new Error(`${source.id}: a ${kind} stroke needs a start and one more point`);
    const start = points[0]!;
    const [ra0, dec0] = local(start[0], start[1]);
    previousRa = wrapRa(ra0);
    let cursor: Pair = [round(previousRa), round(dec0)];
    out += `M${text(cursor[0])} ${text(cursor[1])}${kind === "L" ? "l" : "r"}`;
    const steps: string[] = [];
    for (const p of points.slice(1)) {
      const [ra, dec] = local(p[0], p[1]);
      let r = ra;
      while (r - previousRa > 180) r -= 360;
      while (r - previousRa < -180) r += 360;
      previousRa = r;
      const next: Pair = [round(r), round(dec)];
      steps.push(`${text(next[0] - cursor[0])} ${text(next[1] - cursor[1])}`);
      cursor = next;
    }
    out += steps.join(" ") + (kind === "O" ? "z" : "");
  }
  return out;
}

function wrapRa(value: number): number {
  return ((value % 360) + 360) % 360;
}

const rows = SOURCES.map((source) => {
  const found = constellation(source.constellation)!;
  return [source.id, source.constellation, source.english ?? found.english, source.japanese ?? found.japanese, flat(source)];
});
const text = `// GENERATED by scripts/make-figure-data.ts from scripts/figure-sources.ts. Do not edit by hand.
// Our own drawings, not copies of anyone's: see NOTICE.md. One row a figure: key | constellation | English name | Japanese name | path in degrees of right ascension and declination, J2000.

/** The figures, one row each. */
export const FIGURE_ROWS: ReadonlyArray<readonly [string, string, string, string, string]> = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(fileURLToPath(new URL("../src/data/figures.ts", import.meta.url)), text);
for (const row of rows) console.log(row[0], String(row[4]).length, "characters");
