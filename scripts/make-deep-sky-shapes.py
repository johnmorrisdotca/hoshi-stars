#!/usr/bin/env python3
"""Write src/data/deep-sky-shapes-messier.ts and src/data/deep-sky-shapes-ngc-ic.ts: how big each deep-sky object is on the sky, and which way it lies.

The objects are those of src/data/messier.ts and src/data/ngc-ic.ts (Wikidata, CC0). Their sizes are measurements from three catalogues that NASA's HEASARC serves; NOTICE.md
records what each is and the date it was read:

- RC3, the Third Reference Catalogue of Bright Galaxies (de Vaucouleurs et al. 1991; HEASARC table `rc3`): for a galaxy, the major diameter at the B-band 25 mag/arcsec^2
  isophote (D25), the axis ratio (R25) and the position angle of the major axis, east of north.
- The Messier table (HEASARC table `messier`, from Sky Catalog 2000.0 Vol. 2): a major and often a minor diameter, for the Messier objects.
- NGC 2000.0 (Sinnott 1988; HEASARC table `ngc2000`): one diameter, for nearly every NGC and IC object.

What an object gets, first that has it:
- a Messier galaxy or an NGC or IC galaxy: RC3's major diameter, axis ratio and position angle (where RC3 has each), else the Messier table's, else NGC 2000.0's major diameter;
- any other Messier object: the Messier table's major (and minor) diameter;
- any other NGC or IC object: NGC 2000.0's diameter;
- and for any object that these leave without a size, the size Wikidata gave it (`sizeArcmin` of the object).
No position angle exists outside RC3, and none is invented. A row is `id | major | minor | angle | source`: the major and minor diameters in tenths of an arc-minute (minor left empty
where unknown), the angle in whole degrees east of north (0 to 179, empty where unknown) and one letter for the catalogue (r RC3, m Messier table, n NGC 2000.0, w Wikidata).

    python3 -I scripts/make-deep-sky-shapes.py                 # downloads the three tables (needs the network)
    python3 -I scripts/make-deep-sky-shapes.py --from DIR      # reads heasarc_rc3.tdat.gz, heasarc_ngc2000.tdat.gz and heasarc_messier.tdat.gz saved in DIR

None of this runs in the test.
"""
import gzip
import math
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = "https://heasarc.gsfc.nasa.gov/FTP/heasarc/dbase/tdat_files/"
TABLES = ["rc3", "ngc2000", "messier"]
USER_AGENT = "hoshi-stars-data-script/0.1 (https://github.com/johnmorrisdotca/hoshi-stars)"
GALAXY = 1  # the index of "galaxy" in DEEP_SKY_TYPES

HEADER = """// GENERATED by scripts/make-deep-sky-shapes.py. Do not edit by hand.
// How big each deep-sky object is on the sky and which way it lies, from RC3, the Messier table and NGC 2000.0 as NASA's HEASARC serves them (the sources are in NOTICE.md).
// One row an object: id (`M31`, `N7000` for NGC 7000, `I434` for IC 434) | major diameter in tenths of an arc-minute | minor diameter (tenths; empty where unknown) |
// position angle of the major axis, whole degrees east of north (empty where unknown) | source (r RC3, m Messier table, n NGC 2000.0, w Wikidata).
"""


def load(name, folder):
    if folder is not None:
        return gzip.open(folder / f"heasarc_{name}.tdat.gz", "rt", encoding="utf-8", errors="replace").read()
    request = urllib.request.Request(BASE + f"heasarc_{name}.tdat.gz", headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=300) as answer:
        return gzip.decompress(answer.read()).decode("utf-8", errors="replace")


def table(text):
    """The rows of a .tdat table as dicts keyed by the names of its `line[1]` header."""
    names = re.search(r"^line\[1\] = (.*)$", text, re.M).group(1).split()
    body = text.split("<DATA>\n", 1)[1].split("<END>")[0]
    return [dict(zip(names, line.split("|"))) for line in body.split("\n") if line != ""]


def designation(text):
    """`NGC 224`, `NGC224`, `IC 4725` and `NGC 2573A` as ("NGC", "224", "") or None."""
    found = re.fullmatch(r"(NGC|IC) ?0*(\d+) ?([A-Za-z]?)", text.strip())
    return None if found is None else (found.group(1), found.group(2), found.group(3).upper())


def objects():
    """The Wikidata objects of the two data files: dicts with id, messier, names (the designations), type, ra, dec and size (arc-minutes or None)."""
    found = []
    for name, constant in (("messier", "MESSIER_ROWS"), ("ngc-ic", "NGC_IC_ROWS")):
        text = (ROOT / "src" / "data" / f"{name}.ts").read_text(encoding="utf-8")
        rows = re.search(constant + r" = `(.*?)`;", text, re.S).group(1).split("\n")
        for row in rows:
            p = row.split("|")
            messier = f"M{p[0]}" if p[0] != "" else None
            ngc = [("NGC", n[:-1] if n[-1:].isalpha() else n, n[-1:] if n[-1:].isalpha() else "") for n in p[1].split(",") if n != ""]
            ic = [("IC", n[:-1] if n[-1:].isalpha() else n, n[-1:] if n[-1:].isalpha() else "") for n in p[2].split(",") if n != ""]
            names = ngc + ic
            first = messier or (f"NGC {ngc[0][1]}{ngc[0][2]}" if ngc else f"IC {ic[0][1]}{ic[0][2]}")
            found.append({"id": first, "messier": messier, "names": names, "type": int(p[3]), "ra": int(p[4]) / 10000, "dec": int(p[5]) / 10000, "size": int(p[7]) / 10 if p[7] != "" else None})
    return found


def separation(ra1, dec1, ra2, dec2):
    """Degrees between two positions."""
    a, b, c, d = map(math.radians, (ra1, dec1, ra2, dec2))
    x = math.sin(b) * math.sin(d) + math.cos(b) * math.cos(d) * math.cos(a - c)
    return math.degrees(math.acos(max(-1.0, min(1.0, x))))


def number(text):
    try:
        return float(text)
    except ValueError:
        return None


def main():
    folder = None
    if "--from" in sys.argv:
        folder = Path(sys.argv[sys.argv.index("--from") + 1])
    rc3_rows, ngc_rows, messier_rows = (table(load(name, folder)) for name in TABLES)

    rc3 = {}
    for row in rc3_rows:
        d25 = number(row["log_d25"])
        if d25 is None:
            continue
        for key in (row["name"], row["alt_name_1"], row["alt_name_2"]):
            d = designation(key)
            if d is not None and d not in rc3:
                rc3[d] = row
    ngc2000 = {}
    for row in ngc_rows:
        d = designation(row["name"])
        size = number(row["ang_diameter"])
        if d is not None and size is not None and size > 0 and row["limit_ang_diameter"] == "":
            ngc2000[d] = (size, row)
    messier = {}
    for row in messier_rows:
        found = re.fullmatch(r"M ?(\d+)", row["name"].strip())
        dims = row["dimension"].strip().upper()
        if found is None or dims == "":
            continue
        parts = [number(part) for part in dims.split("X")]
        if parts[0] is None or parts[0] <= 0:
            continue
        messier[f"M{found.group(1)}"] = (parts[0], parts[1] if len(parts) > 1 and parts[1] else None)

    out = {"messier": [], "ngc-ic": []}
    counts = {}
    rejected = []
    for o in objects():
        entry = None  # (major, minor, angle, source)
        rc3_row = None
        if o["type"] == GALAXY:
            for d in o["names"]:
                row = rc3.get(d)
                if row is not None and separation(o["ra"], o["dec"], float(row["ra"]), float(row["dec"])) * 60 < max(6.0, 0.6 * 10 ** number(row["log_d25"]) / 10):
                    rc3_row = row
                    break
                if row is not None:
                    rejected.append((o["id"], row["name"]))
        if rc3_row is not None:
            major = 10 ** number(rc3_row["log_d25"]) / 10
            ratio = 10 ** number(rc3_row["log_r25"]) if number(rc3_row["log_r25"]) is not None else None
            angle = number(rc3_row["position_angle"])
            minor = major / ratio if ratio is not None and ratio >= 1 else None
            entry = (major, minor, None if angle is None or minor is None or minor > 0.97 * major else int(angle) % 180, "r")
        if entry is None and o["messier"] in messier:
            major, minor = messier[o["messier"]]
            entry = (major, minor, None, "m")
        if entry is None:
            for d in o["names"]:
                if d in ngc2000:
                    entry = (ngc2000[d][0], None, None, "n")
                    break
        if entry is None and o["size"] is not None:
            entry = (o["size"], None, None, "w")
        if entry is None:
            continue
        counts[entry[3]] = counts.get(entry[3], 0) + 1
        short = o["id"].replace("NGC ", "N").replace("IC ", "I")
        major, minor, angle, source = entry
        row = f"{short}|{round(major * 10)}|{'' if minor is None else round(min(minor, major) * 10)}|{'' if angle is None else angle}|{source}"
        out["messier" if o["messier"] else "ngc-ic"].append(row)

    for name, constant, note in (("messier", "MESSIER_SHAPES", "The Messier objects that have a size, one per line."), ("ngc-ic", "NGC_IC_SHAPES", "The NGC and IC objects that are not Messier objects and have a size, one per line.")):
        (ROOT / "src" / "data" / f"deep-sky-shapes-{name}.ts").write_text(HEADER + f"\n/** {note} */\nexport const {constant} = `" + "\n".join(out[name]) + "`;\n", encoding="utf-8")
    angled = sum(1 for rows in out.values() for row in rows if row.split("|")[3] != "")
    ratioed = sum(1 for rows in out.values() for row in rows if row.split("|")[2] != "")
    print(f"rows: messier {len(out['messier'])}, ngc-ic {len(out['ngc-ic'])}; by source {counts}; with a minor axis {ratioed}; with an angle {angled}; rc3 rows rejected for position {len(rejected)}")
    for pair in rejected[:10]:
        print("  rejected", pair)


if __name__ == "__main__":
    main()
